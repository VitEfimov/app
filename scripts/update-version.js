#!/usr/bin/env node
/**
 * Auto-upgrades src/versionInfo.js whenever the git commit count or hash changes.
 * - Major.Minor read from app.json (default "1.0")
 * - Patch = Git commit count (upgrades automatically with every commit)
 * - Random 4-digit build number (1000-9999) refreshed whenever the commit advances
 *
 * Usage:
 *   node scripts/update-version.js          # Updates if commit changed (or file missing)
 *   node scripts/update-version.js --next   # Pre-commit mode: uses HEAD count + 1 and fresh random number
 *   node scripts/update-version.js --force  # Always refreshes random build number
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execSync } = require('child_process');

const rootDir = path.resolve(__dirname, '..');
const appJsonPath = path.join(rootDir, 'app.json');
const outPath = path.join(rootDir, 'src', 'versionInfo.js');

const isNext = process.argv.includes('--next');
const isForce = process.argv.includes('--force');

let baseVersion = '1.0';
try {
  const appJson = JSON.parse(fs.readFileSync(appJsonPath, 'utf8'));
  const rawVer = String(appJson?.expo?.version || '1.0.0');
  const parts = rawVer.split('.');
  if (parts.length >= 2) {
    baseVersion = `${parts[0]}.${parts[1]}`;
  }
} catch (e) {}

let prevInfo = null;
try {
  if (fs.existsSync(outPath)) {
    const rawJs = fs.readFileSync(outPath, 'utf8');
    const match = rawJs.match(/export const APP_VERSION_INFO = (\{[\s\S]*?\});/);
    if (match) {
      prevInfo = JSON.parse(match[1]);
    }
  }
} catch (e) {}

let commitCount = prevInfo?.commitCount || 1;
try {
  const rawCount = execSync('git rev-list --count HEAD', { cwd: rootDir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  const parsed = parseInt(rawCount, 10);
  if (!isNaN(parsed) && parsed > 0) {
    commitCount = isNext ? parsed + 1 : parsed;
  }
} catch (e) {
  if (isNext) commitCount += 1;
}

let commitHash = prevInfo?.commitHash || 'dev';
try {
  commitHash = execSync('git rev-parse --short HEAD', { cwd: rootDir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || commitHash;
} catch (e) {}

// If already up to date for this commit and not forced/--next, keep existing random number stable
if (
  !isNext &&
  !isForce &&
  prevInfo &&
  prevInfo.baseVersion === baseVersion &&
  prevInfo.commitCount === commitCount &&
  prevInfo.commitHash === commitHash &&
  typeof prevInfo.buildRandom === 'number' &&
  prevInfo.displayVersion
) {
  console.log(`[update-version] Up to date -> ${prevInfo.displayVersion}`);
  process.exit(0);
}

const buildRandom = crypto.randomInt(1000, 10000);
const version = `${baseVersion}.${commitCount}`;
const displayVersion = `${version} (${buildRandom})`;

const payload = {
  version,
  baseVersion,
  commitCount,
  buildRandom,
  commitHash,
  displayVersion,
  updatedAt: new Date().toISOString(),
};

const fileContents =
  `// Auto-generated by scripts/update-version.js (upgrades automatically with git commits)\n` +
  `export const APP_VERSION_INFO = ${JSON.stringify(payload, null, 2)};\n\n` +
  `export default APP_VERSION_INFO;\n`;

fs.writeFileSync(outPath, fileContents, 'utf8');
console.log(`[update-version] Updated src/versionInfo.js -> ${displayVersion}`);
